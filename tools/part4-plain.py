# 1. Every View move opens with a clear opinion phrase, rotating so students hear each one
#    often: In my view / The way I see it / I really think / My own view is that, plus the
#    familiar ones. 2. Reasons are signposted ('The reason is that…', 'That's why…',
#    'As a result…'). 3. No British fillers ('Mind you', 'To be fair'), dashes or 'Hmm'.
# OV: hand edits, key card/version/part/move -> new text (applied last).
import re
OPENERS = ["In my view,", "The way I see it,", "I really think", "My own view is that",
           "I think", "In my opinion,", "I'd say", "I believe"]
STRIP = r"^(I think|I'd say|In my opinion,|I believe|For me,|Personally,|I really think|In my view,)\s+"
def opener(n, t):
    o = OPENERS[n % len(OPENERS)]
    body = re.sub(STRIP, "", t)
    if body == t:                       # no opener to replace: keep the sentence, put the phrase in front
        body = body[0].lower() + body[1:] if not body.startswith("I ") and not body.startswith("I'") else body
    return f"{o} {body}"

